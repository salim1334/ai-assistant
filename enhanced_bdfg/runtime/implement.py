"""Generate a runnable assistant package (Alarm CRM or generic)."""

from __future__ import annotations

import json
import os
from typing import Any, Dict

from enhanced_bdfg.industry_specific.fmcg_distribution.domain import AlarmCRMDomain
from enhanced_bdfg.industry_specific.fmcg_distribution.sample_data import seed_sample_addis
from enhanced_bdfg.runtime.coordinator import AttentiveCoordinator, default_memory_path


README = """# Alarm CRM assistant (generated by BDFG)

This package is a local Alarm CRM core plus an attentive business-developer assistant.

Not included in v1: native retailer apps, live Telebirr/Chapa capture, AWS multi-tenant hosting.

Sample kiosk/order data is synthetic Addis Ababa demand for demos — not real market data.

Talk to it with `bdfg start` or:

```
bdfg chat --root {root}
```
"""


def implement_alarm_crm(output_dir: str, seed: bool = True) -> Dict[str, Any]:
    os.makedirs(output_dir, exist_ok=True)
    db_path = os.path.join(output_dir, "alarm_crm.sqlite")
    mem_dir = os.path.join(output_dir, "memory")
    os.makedirs(mem_dir, exist_ok=True)
    domain = AlarmCRMDomain(db_path)
    seed_info: Dict[str, Any] = {}
    if seed:
        seed_info = seed_sample_addis(domain)
    config = {
        "name": "Alarm CRM Assistant",
        "industry": "fmcg_distribution",
        "pack": "alarm-crm",
        "db_path": db_path,
        "memory_path": default_memory_path(output_dir),
        "self_improvement": {"enabled": True},
        "model": {"backend": "local", "local_model": ""},
        "adapters": ["alarm_stock", "smart_bono", "et_property", "telebirr", "chapa", "sms"],
        "sample": seed_info,
    }
    cfg_path = os.path.join(output_dir, "assistant.json")
    existing: Dict[str, Any] = {}
    if os.path.exists(cfg_path):
        try:
            with open(cfg_path, encoding="utf-8") as fh:
                existing = json.load(fh)
        except json.JSONDecodeError:
            existing = {}
    existing.update(config)
    with open(cfg_path, "w", encoding="utf-8") as fh:
        json.dump(existing, fh, indent=2)
    with open(os.path.join(output_dir, "README.md"), "w", encoding="utf-8") as fh:
        fh.write(README.format(root=output_dir))
    domain.close()
    return {"output_dir": output_dir, "config": cfg_path, "db_path": db_path, "sample": seed_info}


def load_coordinator(root: str, user_id: str = "default") -> AttentiveCoordinator:
    cfg_path = os.path.join(root, "assistant.json")
    db_path = os.path.join(root, "alarm_crm.sqlite")
    cfg: Dict[str, Any] = {}
    if os.path.exists(cfg_path):
        with open(cfg_path, encoding="utf-8") as fh:
            cfg = json.load(fh)
        db_path = cfg.get("db_path") or db_path
        mem = cfg.get("memory_path") or default_memory_path(root)
    else:
        mem = default_memory_path(root)
    domain = None
    if cfg.get("pack") == "alarm-crm" or (db_path and os.path.exists(str(db_path))):
        domain = AlarmCRMDomain(db_path)
    persona = ""
    persona_path = cfg.get("persona_path") or os.path.join(root, "persona.md")
    if os.path.exists(persona_path):
        with open(persona_path, encoding="utf-8") as fh:
            persona = fh.read()
    language = cfg.get("language") or "en"
    tenant = "alarm" if domain is not None else "default"
    return AttentiveCoordinator(
        memory_path=mem,
        domain=domain,
        user_id=user_id,
        tenant_id=tenant,
        language=language,
        persona=persona,
        model_config=cfg.get("model") or {},
    )
